def stage_render(image_files: list[Path], audio_files: list[Path],
                 durations: list[int], work_dir: Path, output_path: Path) -> bool:
    """Render video với FFmpeg VideoToolbox HW."""
    print("🎬 STAGE 4: RENDER...")

    temp_dir = work_dir / "temp_segments"
    temp_dir.mkdir(parents=True, exist_ok=True)

    # Render từng segment
    segment_files = []
    for i, (img, dur) in enumerate(zip(image_files, durations)):
        seg_file = temp_dir / f"seg_{i:03d}.mp4"
        print(f"   [{i+1}/{len(image_files)}] {dur}s", end=" ")

        result = subprocess.run([
            "ffmpeg", "-y", "-loglevel", "error",
            "-loop", "1", "-t", str(dur), "-i", str(img),
            "-vf", f"scale={RESOLUTION[0]}:{RESOLUTION[1]}:force_original_aspect_ratio=decrease,"
                   f"pad={RESOLUTION[0]}:{RESOLUTION[1]}:(ow-iw)/2:(oh-ih)/2,setsar=1,fps={FPS}",
            "-c:v", "h264_videotoolbox", "-b:v", "8M", "-allow_sw", "1",
            "-pix_fmt", "yuv420p", "-r", str(FPS), "-an",
            str(seg_file),
        ], capture_output=True)
        if result.returncode == 0:
            segment_files.append(seg_file)
            print("OK")
        else:
            print(f"FAIL: {result.stderr[-200:]}")

    if not segment_files:
        return False

    # Concat video
    concat_list = temp_dir / "concat.txt"
    with open(concat_list, "w") as f:
        for sf in segment_files:
            f.write(f"file '{sf.absolute()}'\n")

    video_silent = temp_dir / "video_silent.mp4"
    result = subprocess.run([
        "ffmpeg", "-y", "-loglevel", "error",
        "-f", "concat", "-safe", "0", "-i", str(concat_list),
        "-c:v", "copy",
        str(video_silent),
    ], capture_output=True)
    if result.returncode != 0:
        print(f"   ❌ Concat failed")
        return False

    # Concat audio
    audio_list = temp_dir / "audio_list.txt"
    with open(audio_list, "w") as f:
        for af in audio_files:
            f.write(f"file '{af.absolute()}'\n")

    audio_full = temp_dir / "audio_full.aac"
    result = subprocess.run([
        "ffmpeg", "-y", "-loglevel", "error",
        "-f", "concat", "-safe", "0", "-i", str(audio_list),
        "-c:a", "aac", "-b:a", "320k",
        str(audio_full),
    ], capture_output=True)
    if result.returncode != 0:
        print(f"   ❌ Audio concat failed")
        return False

    # Combine
    print("   Combining video + audio...", end=" ")
    result = subprocess.run([
        "ffmpeg", "-y", "-loglevel", "error",
        "-i", str(video_silent), "-i", str(audio_full),
        "-c:v", "h264_videotoolbox", "-b:v", "8M", "-allow_sw", "1",
        "-c:a", "aac", "-b:a", "320k",
        "-shortest", "-movflags", "+faststart",
        str(output_path),
    ], capture_output=True)
    if result.returncode != 0:
        print(f"FAIL: {result.stderr[-200:]}")
        return False

    # Verify
    probe = subprocess.run(["ffprobe", str(output_path)], capture_output=True, text=True).stderr
    has_video = "Video:" in probe
    has_audio = "Audio:" in probe
    size_mb = output_path.stat().st_size / (1024 * 1024)

    if has_video and has_audio:
        print(f"OK ({size_mb:.0f}MB)")
        return True

    print(f"❌ Verify failed: video={has_video}, audio={has_audio}")
    return False


# ═══════════════════════════════════════════════════════════
# STAGE 5: CLEANUP
# ═══════════════════════════════════════════════════════════

def stage_cleanup(work_dir: Path, output_path: Path, topic: str):
    """Xoá toàn bộ temp files, chỉ giữ MP4 + production log."""
    print("🧹 CLEANUP...")

    # Move final video to safe location temporarily
    safe_copy = output_path.parent / output_path.name

    # Delete working directory
    if work_dir.exists():
        shutil.rmtree(work_dir)
        print(f"   Deleted: {work_dir}")

    # Also clean images and audio directories for this topic
    for subdir in ["images", "audio"]:
        topic_dir = ROOT / "channels" / CHANNEL / subdir / topic
        if topic_dir.exists():
            shutil.rmtree(topic_dir)
            print(f"   Deleted: {topic_dir}")

    # Clean manifest
    manifest = ROOT / "engine" / "manifest" / "active" / f"{topic}.json"
    if manifest.exists():
        manifest.unlink()
        print(f"   Deleted: {manifest}")

    # Production log
    log_file = ROOT / "channels" / CHANNEL / "video" / "production_log.jsonl"
    entry = {
        "date": datetime.now().strftime("%Y-%m-%d"),
        "topic": topic,
        "file": output_path.name,
        "size_mb": round(safe_copy.stat().st_size / (1024 * 1024), 1),
    }
    with open(log_file, "a") as f:
        f.write(json.dumps(entry) + "\n")

    print(f"✅ Cleanup done. Only kept: {safe_copy}")
    print(f"📋 Log: {log_file}")


