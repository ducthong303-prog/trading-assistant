def preflight() -> bool:
    """Kiểm tra tất cả dependencies trước khi generate."""
    print("🔍 PRE-FLIGHT CHECK...")
    errors = []

    # FFmpeg
    if shutil.which("ffmpeg") is None:
        errors.append("FFmpeg chưa cài. Chạy: brew install ffmpeg")

    # KieAI
    try:
        import requests
        r = requests.get("https://api.kie.ai/api/v1/gpt4o-image/generate",
                         headers={"Authorization": f"Bearer {require_env('KIEAI_API_KEY')}"},
                         timeout=10)
        if r.status_code == 401:
            errors.append("KieAI API key không hợp lệ")
        elif r.status_code == 402:
            errors.append("KieAI hết credit")
    except Exception as e:
        errors.append(f"KieAI không kết nối được: {e}")

    # ElevenLabs
    try:
        r = requests.get("https://api.elevenlabs.io/v1/voices",
                         headers={"xi-api-key": require_env("ELEVENLABS_API_KEY")},
                         timeout=10)
        if r.status_code == 401:
            errors.append("ElevenLabs API key không hợp lệ")
    except Exception as e:
        errors.append(f"ElevenLabs không kết nối được: {e}")

    # Disk
    disk = shutil.disk_usage(ROOT)
    if disk.free < 2 * 1024**3:
        errors.append(f"Disk còn < 2GB ({disk.free // 1024**3}GB)")

    if errors:
        print("❌ PRE-FLIGHT FAILED:")
        for e in errors:
            print(f"   - {e}")
        return False

    print("✅ PRE-FLIGHT OK\n")
    return True


