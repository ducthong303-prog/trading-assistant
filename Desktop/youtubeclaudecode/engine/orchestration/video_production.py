def stage_images(prompts: list[str], work_dir: Path) -> list[Path]:
    """Generate ảnh qua KieAI 4o. Verify content-type. Retry 1x."""
    print(f"🎨 STAGE 2: IMAGES ({len(prompts)} ảnh)...")

    from engine.providers.kieai_4o import KieAI4oClient
    client = KieAI4oClient(logger=log)

    img_dir = work_dir / "images"
    img_dir.mkdir(parents=True, exist_ok=True)

    items = []
    for i, prompt in enumerate(prompts):
        items.append({
            "id": f"img_{i+1:03d}",
            "prompt": prompt,
            "size": "3:2",
        })

    results = client.generate_batch(items, img_dir, parallel=5)
    ok, failed = 0, 0
    for r in results:
        if r["success"]:
            # Verify content-type
            fp = Path(r["path"])
            file_type = subprocess.run(["file", "-b", str(fp)], capture_output=True, text=True).stdout
            if "HTML" in file_type or "html" in file_type:
                print(f"   ❌ {r['id']}: got HTML instead of image — retrying...")
                # Retry once
                r2 = client.generate_and_save(items[[i["id"] for i in items].index(r["id"])]["prompt"], fp)
                if r2["success"]:
                    ok += 1
                else:
                    failed += 1
            else:
                ok += 1
        else:
            failed += 1

    print(f"   ✅ {ok} OK, ❌ {failed} failed")
    if failed > 0:
        print(f"   ⚠️  {failed} ảnh fail — tiếp tục với ảnh đã có")

    return sorted(img_dir.glob("img_*.jpeg"))


# ═══════════════════════════════════════════════════════════
# STAGE 3: TTS
# ═══════════════════════════════════════════════════════════

def stage_tts(text: str, work_dir: Path) -> list[Path]:
    """Generate audio qua ElevenLabs. Split thành ~6 chunks."""
    print("🎙️  STAGE 3: TTS...")

    from engine.providers.elevenlabs import ElevenLabsClient
    client = ElevenLabsClient(logger=log)

    audio_dir = work_dir / "audio"
    audio_dir.mkdir(parents=True, exist_ok=True)

    # Split text into ~4000 char chunks
    text = text.strip()
    total = len(text)
    n_chunks = max(2, min(6, total // TTS_CHUNK_CHARS))
    chunk_size = total // n_chunks

    chunks = []
    cursor = 0
    for ci in range(n_chunks):
        end = min(cursor + chunk_size, total) if ci < n_chunks - 1 else total
        # Extend to nearest paragraph break
        if end < total:
            next_break = text.find("\n\n", end)
            if next_break != -1 and next_break - end < 500:
                end = next_break
        chunk_text = text[cursor:end].strip()
        if chunk_text:
            chunks.append({"id": f"tts_chunk{ci+1:02d}", "text": chunk_text})
        cursor = end

    print(f"   {len(chunks)} chunks (~{chunk_size} chars each)")

    results = client.generate_narration_chunks(chunks, audio_dir)

    audio_files = []
    for r in results:
        if r["success"]:
            audio_files.append(Path(r["path"]))
        else:
            print(f"   ❌ {r['id']}: {r.get('error', 'unknown')}")

    print(f"   ✅ {len(audio_files)}/{len(chunks)} audio files")
    return sorted(audio_files)


# ═══════════════════════════════════════════════════════════
# STAGE 4: RENDER
